// Regenerates items.tsv: every item prefab with the numbers valheim-save
// needs to put one into a character file, and the English name the game
// shows for it.
//
//	go run ./internal/character/items_gen.go -items <items.tsv> -english <English.json>
//
// The items file is tools/item-dump.cs's output, run inside a game server:
// the prefab, its type, stack size, quality cap, durability and per-level
// durability, whether durability is used, whether it teleports, its weight
// and its name token. The English file is the game's localization table as
// token to text (valheim-npc's unity-meshes -localization writes one); a name
// without a '$' is already the text, which is how creature attacks are
// named. Creature attacks and the like are items to the game and come
// through, so the table is the game's, not a curated one.
package main

import (
	"bufio"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"
)

func main() {
	itemsPath := flag.String("items", "", "tools/item-dump.cs's output")
	englishPath := flag.String("english", "", "the game's English text, token to text")
	out := flag.String("out", "internal/character/items.tsv", "where to write the table")
	flag.Parse()
	if *itemsPath == "" || *englishPath == "" {
		flag.Usage()
		os.Exit(2)
	}
	english := map[string]string{}
	data, err := os.ReadFile(*englishPath)
	if err != nil {
		fail(err)
	}
	if err := json.Unmarshal(data, &english); err != nil {
		fail(err)
	}
	var rows []string
	named, unnamed := 0, 0
	for _, line := range lines(*itemsPath) {
		f := strings.Split(line, "\t")
		if len(f) != 10 {
			fail(fmt.Errorf("items.tsv: %d columns in %q", len(f), line))
		}
		name := f[9]
		if strings.HasPrefix(name, "$") {
			if text, ok := english[name]; ok && text != "" {
				name = text
				named++
			} else {
				name = ""
				unnamed++
			}
		}
		rows = append(rows, strings.Join(append(f[:9], name), "\t"))
	}
	sort.Strings(rows)
	table := "# prefab\ttype\tstack\tmaxQuality\tmaxDurability\tdurabilityPerLevel\tuseDurability\tteleportable\tweight\tname\n" +
		"# Generated by internal/character/items_gen.go from tools/item-dump.cs's output and the game's English text.\n" +
		strings.Join(rows, "\n") + "\n"
	if err := os.WriteFile(*out, []byte(table), 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("%d items, %d with English names, %d without\n", len(rows), named, unnamed)
}

func lines(path string) []string {
	f, err := os.Open(path)
	if err != nil {
		fail(err)
	}
	defer f.Close()
	var out []string
	s := bufio.NewScanner(f)
	s.Buffer(make([]byte, 1<<20), 1<<20)
	for s.Scan() {
		if line := s.Text(); line != "" && !strings.HasPrefix(line, "#") {
			out = append(out, line)
		}
	}
	return out
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "error:", err)
	os.Exit(1)
}
